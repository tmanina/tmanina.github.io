/** يزيل التشكيل وعلامات التوضيح وعلامات الوقف لتسهيل البحث العربي */
export function normalizeArabic(text: string): string {
  return text
    .replace(/[\u064B-\u0652\u0653-\u0655\u0670\u06D6-\u06ED]/g, '') // تشكيل وعلامات تلاوة
    .replace(/[\u0640]/g, '') // تطويل
    .replace(/[إأآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
}

