/** Convert a number to Arabic numerals */
export function toArabicNumeral(num: number): string {
  const arabicNumerals = ["٠", "١", "٢", "٣", "٤", "٥", "٦", "٧", "٨", "٩"]
  return num.toString().split("").map((d) => arabicNumerals[parseInt(d)]).join("")
}

/** Get juz number for a given page */
export function getJuzNumber(page: number): number {
  for (let i = 30; i >= 1; i--) {
    if (page >= juzStartPages[i]) return i
  }
  return 1
}

/** Get surah info from a verse_key */
export function getSurahInfo(verseKey: string) {
  const surahNum = parseInt(verseKey.split(":")[0])
  return { number: surahNum, name: surahNames[surahNum] || `سورة ${toArabicNumeral(surahNum)}` }
}

/** Clean text from unwanted characters (waqf marks, asterisks) */
export function cleanText(text: string): string {
  if (!text) return ""
  return text.replace(/\*/g, "").replace(/[\u06D6-\u06ED]/g, "")
}
